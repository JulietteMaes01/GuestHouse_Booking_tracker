def country_of_international_number(digits: str) -> tuple[str, str] | None:
    """(ISO code, French name) for digits starting with a country code, e.g. '32470…'."""
    for length in (3, 2, 1):
        country = PHONE_CODES.get(digits[:length])
        if country is None:
            continue
        if digits[:1] == "1" and digits[1:4] in CANADA_AREA_CODES:
            return CANADA
        if digits[:1] == "7" and digits[1:2] in ("6", "7"):
            return KAZAKHSTAN
        return country
    return None


def flag(iso_code: str) -> str:
    """'BE' → '🇧🇪' (a flag is the country's two letters as regional-indicator symbols)."""
    return "".join(chr(0x1F1E6 + ord(letter) - ord("A")) for letter in iso_code)
